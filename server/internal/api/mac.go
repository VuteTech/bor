// macStore is the subset of database.MacRepository the handlers need.
type macStore interface {
	GetNodeStatus(ctx context.Context, nodeID string) (*database.MacNodeStatus, error)
	ListItems(ctx context.Context, lsm, kind, q string, limit int) ([]database.MacCatalogueItem, error)
	ListItemsByNode(ctx context.Context, nodeID, lsm, kind, q string, limit int) ([]database.MacCatalogueItem, error)
}

// macActionSender pushes an action to a connected agent (grpc.PolicyHub).
type macActionSender interface {
	SendMacAction(clientID string, action *pb.MacAction) bool
}

const (
	maxMacQueryLength      = 128
	defaultMacListLimit    = 200
	maxMacListLimit        = 1000
	defaultMacActionWindow = 24
	maxMacActionWindow     = 24 * 14
	// DefaultMacActionTimeout is how long a proposal request waits for the
	// agent: reading a day of journal and running audit2allow takes a few
	// seconds on a desktop.
	DefaultMacActionTimeout = 60 * time.Second
)

var macMarshal = protojson.MarshalOptions{UseProtoNames: false, EmitUnpopulated: true}

// macItemResponse is one catalogue or node inventory row as the UI
// consumes it: the reported item plus the server's curated knowledge.
type macItemResponse struct {
	LSM        string          `json:"lsm"`
	Kind       string          `json:"kind"`
	Name       string          `json:"name"`
	NodeCount  int             `json:"nodeCount"`
	ReportedAt *time.Time      `json:"reportedAt,omitempty"`
	Info       json.RawMessage `json:"info"`
	// Curated fields (SELinux booleans and AppArmor profile files).
	Group       string `json:"group,omitempty"`
	Description string `json:"description,omitempty"`
	Restrictive *bool  `json:"restrictive,omitempty"`
	// RiskyOn / RiskyOff: setting a boolean to that value deserves a
	// confirmation; Risky: disabling the module or profile does.
	RiskyOn   bool `json:"riskyOn,omitempty"`
	RiskyOff  bool `json:"riskyOff,omitempty"`
	Risky     bool `json:"risky,omitempty"`
	Protected bool `json:"protected,omitempty"`
	// Dynamic profiles are generated by their owner and cannot be managed.
	Dynamic bool `json:"dynamic,omitempty"`
	// Curated rows come from the server's list only; no node reported them.
	Curated bool `json:"curated,omitempty"`
}

func macKindValid(lsm, kind string) bool {
	switch lsm {
	case "selinux":
		return kind == database.MacKindBoolean || kind == database.MacKindModule
	case "apparmor":
		return kind == database.MacKindProfile
	}
	return false
}

func macListLimit(raw string) int {
	n, err := strconv.Atoi(raw)
	if err != nil || n <= 0 {
		return defaultMacListLimit
	}
	return min(n, maxMacListLimit)
}

// annotateMacItem fills the curated fields of a row from the server's
// lists and the shared rules.
func annotateMacItem(row *macItemResponse) {
	switch row.Kind {
	case database.MacKindBoolean:
		row.RiskyOn = macrules.IsRiskyBoolean(row.Name, true)
		row.RiskyOff = macrules.IsRiskyBoolean(row.Name, false)
		if c := services.CuratedSelinuxBoolean(row.Name); c != nil {
			row.Group, row.Description, row.Restrictive = c.Group, c.Description, c.Restrictive
		}
	case database.MacKindModule:
		row.Risky = macrules.IsRiskyModule(row.Name)
	case database.MacKindProfile:
		var info struct {
			File      string `json:"file"`
			ManagedBy string `json:"managedBy"`
		}
		_ = json.Unmarshal(row.Info, &info)
		file := info.File
		if file == "" && !strings.Contains(row.Name, "/") {
			file = row.Name
		}
		if c := services.CuratedApparmorProfile(file); c != nil {
			row.Description = c.Description
		}
		row.Protected = macrules.IsProtectedProfile(file)
		row.Dynamic = macrules.IsDynamicManaged(info.ManagedBy)
		row.Risky = true
	}
}

// macItemsResponse converts repository rows and appends curated rows no
// node reported, filtered by the same query.
func macItemsResponse(lsm, kind, q string, rows []database.MacCatalogueItem, withCurated bool, limit int) []macItemResponse {
	out := make([]macItemResponse, 0, len(rows))
	seen := make(map[string]struct{}, len(rows))
	for _, r := range rows {
		t := r.ReportedAt
		row := macItemResponse{LSM: lsm, Kind: kind, Name: r.Name, NodeCount: r.NodeCount, ReportedAt: &t, Info: r.InfoJSON}
		annotateMacItem(&row)
		out = append(out, row)
		seen[r.Name] = struct{}{}
	}
	if !withCurated {
		return out
	}
	ql := strings.ToLower(q)
	matches := func(parts ...string) bool {
		if ql == "" {
			return true
		}
		for _, p := range parts {
			if strings.Contains(strings.ToLower(p), ql) {
				return true
			}
		}
		return false
	}
	switch {
	case lsm == "selinux" && kind == database.MacKindBoolean:
		for _, c := range services.CuratedSelinuxBooleans() {
			if len(out) >= limit {
				break
			}
			if _, ok := seen[c.Name]; ok || !matches(c.Name, c.Description, c.Group) {
				continue
			}
			info, _ := json.Marshal(map[string]any{"name": c.Name, "description": c.Description})
			row := macItemResponse{LSM: lsm, Kind: kind, Name: c.Name, Info: info, Curated: true}
			annotateMacItem(&row)
			out = append(out, row)
		}
	case lsm == "apparmor" && kind == database.MacKindProfile:
		for _, c := range services.CuratedApparmorProfiles() {
			if len(out) >= limit {
				break
			}
			if _, ok := seen[c.File]; ok || !matches(c.File, c.Description) {
				continue
			}
			info, _ := json.Marshal(map[string]any{"name": c.File, "file": c.File, "managedBy": "vendor"})
			row := macItemResponse{LSM: lsm, Kind: kind, Name: c.File, Info: info, Curated: true}
			annotateMacItem(&row)
			out = append(out, row)
		}
	}
	return out
}

// MacHandler serves the mandatory access control catalogue to the policy
// editors: the union of what nodes reported plus the curated lists.
type MacHandler struct {
	store macStore
}

// NewMacHandler creates a new MacHandler.
func NewMacHandler(store macStore) *MacHandler {
	return &MacHandler{store: store}
}

// ListCatalogue handles GET /api/v1/mac/catalogue?lsm=&kind=&q=&node_id=&limit=.
func (h *MacHandler) ListCatalogue(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, `{"error":"method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	query := r.URL.Query()
	lsm, kind := query.Get("lsm"), query.Get("kind")
	if !macKindValid(lsm, kind) {
		writeJSONError(w, http.StatusBadRequest, "lsm must be selinux (kind boolean or module) or apparmor (kind profile)")
		return
	}
	q := strings.TrimSpace(query.Get("q"))
	if len(q) > maxMacQueryLength {
		q = q[:maxMacQueryLength]
	}
	limit := macListLimit(query.Get("limit"))
	var (
		rows []database.MacCatalogueItem
		err  error
	)
	nodeID := query.Get("node_id")
	if nodeID != "" {
		rows, err = h.store.ListItemsByNode(r.Context(), nodeID, lsm, kind, q, limit)
	} else {
		rows, err = h.store.ListItems(r.Context(), lsm, kind, q, limit)
	}
	if err != nil {
		log.Printf("Failed to list mac catalogue: %v", err)
		http.Error(w, `{"error":"failed to list catalogue"}`, http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(macItemsResponse(lsm, kind, q, rows, nodeID == "", limit)); err != nil {
		log.Printf("Failed to encode mac catalogue response: %v", err)
	}
}

// MacNodeHandler serves the Mandatory access control section of the node
// details: status, denial summary, the node's items, and proposal actions.
type MacNodeHandler struct {
	nodes        nodeLookup
	store        macStore
	sender       macActionSender
	broker       *services.MacActionBroker
	auditSvc     *services.AuditService
	anonymizeIPs bool
	timeout      time.Duration
}

// NewMacNodeHandler creates a MacNodeHandler. sender and broker may be
// nil, in which case actions answer 503.
func NewMacNodeHandler(nodes nodeLookup, store macStore, sender macActionSender, broker *services.MacActionBroker, auditSvc *services.AuditService, anonymizeIPs bool) *MacNodeHandler {
	return &MacNodeHandler{nodes: nodes, store: store, sender: sender, broker: broker, auditSvc: auditSvc, anonymizeIPs: anonymizeIPs, timeout: DefaultMacActionTimeout}
}

func (h *MacNodeHandler) loadNode(w http.ResponseWriter, r *http.Request, id string) (*models.Node, bool) {
	if id == "" || h.nodes == nil {
		http.Error(w, `{"error":"node not found"}`, http.StatusNotFound)
		return nil, false
	}
	node, err := h.nodes.GetNode(r.Context(), id)
	if err != nil || node == nil || !requestScope(r, "node", "view").AllowsAny(node.NodeGroupIDs) {
		http.Error(w, `{"error":"node not found"}`, http.StatusNotFound)
		return nil, false
	}
	return node, true
}

// macNodeResponse is GET /api/v1/nodes/{id}/mac.
type macNodeResponse struct {
	LSM          string            `json:"lsm"`
	Mode         string            `json:"mode"`
	ReportedAt   *time.Time        `json:"reportedAt,omitempty"`
	DenialsSince *time.Time        `json:"denialsSince,omitempty"`
	Selinux      json.RawMessage   `json:"selinux,omitempty"`
	Apparmor     json.RawMessage   `json:"apparmor,omitempty"`
	Denials      []json.RawMessage `json:"denials"`
}

// Get handles GET /api/v1/nodes/{id}/mac.
func (h *MacNodeHandler) Get(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, `{"error":"method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	node, ok := h.loadNode(w, r, r.PathValue("id"))
	if !ok {
		return
	}
	st, err := h.store.GetNodeStatus(r.Context(), node.ID)
	if err != nil {
		log.Printf("Failed to load mac status of node %s: %v", node.ID, err)
		http.Error(w, `{"error":"failed to load status"}`, http.StatusInternalServerError)
		return
	}
	resp := macNodeResponse{Denials: []json.RawMessage{}}
	if node.LSM != nil {
		resp.LSM = *node.LSM
	}
	if node.LSMMode != nil {
		resp.Mode = *node.LSMMode
	}
	if st != nil {
		resp.LSM, resp.Mode = st.LSM, st.Mode
		t := st.ReportedAt
		resp.ReportedAt = &t
		resp.DenialsSince = st.DenialsSince
		if st.Selinux != nil {
			resp.Selinux, _ = macMarshal.Marshal(st.Selinux)
		}
		if st.Apparmor != nil {
			resp.Apparmor, _ = macMarshal.Marshal(st.Apparmor)
		}
		for _, d := range st.Denials {
			if data, err := macMarshal.Marshal(d); err == nil {
				resp.Denials = append(resp.Denials, data)
			}
		}
	}
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(resp); err != nil {
		log.Printf("Failed to encode mac node response: %v", err)
	}
}

// ListItems handles GET /api/v1/nodes/{id}/mac/items?kind=&q=&limit=.
func (h *MacNodeHandler) ListItems(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, `{"error":"method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	node, ok := h.loadNode(w, r, r.PathValue("id"))
	if !ok {
		return
	}
	lsm := ""
	if node.LSM != nil {
		lsm = *node.LSM
	}
	if st, err := h.store.GetNodeStatus(r.Context(), node.ID); err == nil && st != nil {
		lsm = st.LSM
	}
	query := r.URL.Query()
	kind := query.Get("kind")
	if kind == "" {
		if lsm == "apparmor" {
			kind = database.MacKindProfile
		} else {
			kind = database.MacKindBoolean
		}
	}
	if !macKindValid(lsm, kind) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte("[]"))
		return
	}
	q := strings.TrimSpace(query.Get("q"))
	if len(q) > maxMacQueryLength {
		q = q[:maxMacQueryLength]
	}
	limit := macListLimit(query.Get("limit"))
	rows, err := h.store.ListItemsByNode(r.Context(), node.ID, lsm, kind, q, limit)
	if err != nil {
		log.Printf("Failed to list mac items of node %s: %v", node.ID, err)
		http.Error(w, `{"error":"failed to list items"}`, http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(macItemsResponse(lsm, kind, q, rows, false, limit)); err != nil {
		log.Printf("Failed to encode mac items response: %v", err)
	}
}

// macActionRequest is the body of POST /api/v1/nodes/{id}/mac/actions.
type macActionRequest struct {
	Kind        string `json:"kind"`
	Subject     string `json:"subject"`
	WindowHours int    `json:"windowHours"`
}

// macActionResponse is the answer once the agent reported back.
type macActionResponse struct {
	ID      string `json:"id"`
	Kind    string `json:"kind"`
	Subject string `json:"subject"`
	Success bool   `json:"success"`
	Message string `json:"message"`
	Text    string `json:"text"`
}

var macActionKinds = map[string]pb.MacActionKind{
	"selinux_propose_module": pb.MacActionKind_MAC_ACTION_SELINUX_PROPOSE_MODULE,
	"apparmor_propose_rules": pb.MacActionKind_MAC_ACTION_APPARMOR_PROPOSE_RULES,
}

// validateMacAction checks an action request against the shared rules.
func validateMacAction(req *macActionRequest) error {
	kind, ok := macActionKinds[req.Kind]
	if !ok {
		return fmt.Errorf("kind must be selinux_propose_module or apparmor_propose_rules")
	}
	switch kind {
	case pb.MacActionKind_MAC_ACTION_SELINUX_PROPOSE_MODULE:
		if err := macrules.ValidateDomain(req.Subject); err != nil {
			return err
		}
	default:
		if req.Subject == "" || len(req.Subject) > 255 || strings.ContainsAny(req.Subject, "\x00\n\r\"") {
			return fmt.Errorf("subject must be a profile name")
		}
	}
	if req.WindowHours == 0 {
		req.WindowHours = defaultMacActionWindow
	}
	if req.WindowHours < 1 || req.WindowHours > maxMacActionWindow {
		return fmt.Errorf("windowHours must be between 1 and %d", maxMacActionWindow)
	}
	return nil
}

// Action handles POST /api/v1/nodes/{id}/mac/actions: it asks the node's
// agent for a policy proposal built from recent denials and waits for the
// text. Gated by mac:operate; confined to nodes whose every group is in
// the caller's scope. Nothing is applied on the node.
func (h *MacNodeHandler) Action(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, `{"error":"method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	node, ok := h.loadNode(w, r, r.PathValue("id"))
	if !ok {
		return
	}
	if !requestScope(r, "mac", "operate").AllowsAll(node.NodeGroupIDs) {
		denyOutOfScope(w, r, "mac", "operate", node.ID)
		return
	}
	var req macActionRequest
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096)).Decode(&req); err != nil {
		http.Error(w, `{"error":"invalid request body"}`, http.StatusBadRequest)
		return
	}
	req.Kind = strings.ToLower(strings.TrimSpace(req.Kind))
	req.Subject = strings.TrimSpace(req.Subject)
	if err := validateMacAction(&req); err != nil {
		writeJSONError(w, http.StatusBadRequest, err.Error())
		return
	}
	if h.sender == nil || h.broker == nil {
		http.Error(w, `{"error":"proposals are not available"}`, http.StatusServiceUnavailable)
		return
	}
	actionID, results, forget, err := h.broker.NewAction(node.Name)
	if err != nil {
		log.Printf("mac action: %v", err)
		http.Error(w, `{"error":"failed to create action"}`, http.StatusInternalServerError)
		return
	}
	defer forget()
	cmd := &pb.MacAction{Id: actionID, Kind: macActionKinds[req.Kind], Subject: req.Subject, WindowHours: int32(req.WindowHours)} //nolint:gosec // G115: bounded by validateMacAction
	if !h.sender.SendMacAction(node.Name, cmd) {
		h.audit(r, node, actionID, req, "not_connected", "agent not connected")
		http.Error(w, `{"error":"agent not connected"}`, http.StatusServiceUnavailable)
		return
	}
	timer := time.NewTimer(h.timeout)
	defer timer.Stop()
	select {
	case res := <-results:
		outcome := "failed"
		if res.Success {
			outcome = "success"
		}
		h.audit(r, node, actionID, req, outcome, res.Message)
		w.Header().Set("Content-Type", "application/json")
		if err := json.NewEncoder(w).Encode(macActionResponse{ID: actionID, Kind: req.Kind, Subject: req.Subject, Success: res.Success, Message: res.Message, Text: res.Text}); err != nil {
			log.Printf("Failed to encode mac action response: %v", err)
		}
	case <-timer.C:
		h.audit(r, node, actionID, req, "timeout", "no answer from the agent")
		writeJSONError(w, http.StatusGatewayTimeout, fmt.Sprintf("the agent did not answer within %s", h.timeout.Round(time.Second)))
	case <-r.Context().Done():
		h.audit(r, node, actionID, req, "abandoned", "request cancelled before the agent answered")
	}
}

// audit records one proposal request with its outcome.
func (h *MacNodeHandler) audit(r *http.Request, node *models.Node, actionID string, req macActionRequest, outcome, message string) {
	if h.auditSvc == nil {
		return
	}
	username := ""
	var userID *string
	if claims := GetUserFromContext(r.Context()); claims != nil {
		username = claims.Username
		if claims.UserID != "" {
			id := claims.UserID
			userID = &id
		}
	}
	details, _ := json.Marshal(map[string]string{
		"node":      node.Name,
		"kind":      req.Kind,
		"subject":   req.Subject,
		"window_h":  strconv.Itoa(req.WindowHours),
		"action_id": actionID,
		"outcome":   outcome,
		"message":   message,
	})
	h.auditSvc.LogEvent(r.Context(), &models.AuditLog{
		UserID:       userID,
		Username:     username,
		Action:       "mac.action",
		ResourceType: "node",
		ResourceID:   node.ID,
		Details:      string(details),
		IPAddress:    extractAuditIP(r, h.anonymizeIPs),
	})
}
